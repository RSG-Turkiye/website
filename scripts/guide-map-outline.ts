/**
 * Regenerates src/lib/guide-map-outline.ts, the Türkiye shape behind the
 * graduate guide's city map. Needed only if the projection in
 * src/lib/guide-map.ts changes; the outline itself never does.
 *
 * Source: Natural Earth 1:50m admin-0 countries (public domain), as the
 * TopoJSON file in the world-atlas package. Download it once, then:
 *
 *   curl -sLo /tmp/countries-50m.json https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-50m.json
 *   npx tsx scripts/guide-map-outline.ts /tmp/countries-50m.json > src/lib/guide-map-outline.ts
 *
 * TopoJSON is decoded here directly (about fifteen lines) so the site needs
 * no geography package.
 */
import { readFileSync } from 'node:fs';
import { project } from '../src/lib/guide-map';

interface Topo {
  transform: { scale: [number, number]; translate: [number, number] };
  arcs: [number, number][][];
  objects: { countries: { geometries: { id: string; type: string; arcs: number[][] | number[][][] }[] } };
}

const topo = JSON.parse(readFileSync(process.argv[2], 'utf8')) as Topo;
const { scale, translate } = topo.transform;
const arc = (i: number): [number, number][] => {
  let x = 0, y = 0;
  const pts = topo.arcs[i < 0 ? ~i : i].map(([dx, dy]) => { x += dx; y += dy; return [x * scale[0] + translate[0], y * scale[1] + translate[1]] as [number, number]; });
  return i < 0 ? pts.reverse() : pts;
};
const ring = (ids: number[]) => ids.flatMap((id, k) => (k ? arc(id).slice(1) : arc(id)));
const tr = topo.objects.countries.geometries.find((g) => g.id === '792')!;
const polygons = (tr.type === 'MultiPolygon' ? tr.arcs : [tr.arcs]) as number[][][];
const d = polygons.map((poly) => poly.map((ids) => ring(ids).map(([lon, lat], i) => {
  const { x, y } = project(lat, lon);
  return `${i ? 'L' : 'M'}${x.toFixed(1)} ${y.toFixed(1)}`;
}).join('') + 'Z').join('')).join('');
process.stdout.write(`// Generated by scripts/guide-map-outline.ts from Natural Earth (public domain). Do not edit by hand.\nexport const TURKIYE_OUTLINE = '${d}';\n`);
